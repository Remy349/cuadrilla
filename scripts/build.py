#!/usr/bin/env python3
"""Generate OpenCode V2-native agent files from the V1-format sources.

`agents/*.md` (V1 frontmatter) is the single source of truth. Both OpenCode 1.x and 2.x
read it: V2 translates V1 frontmatter on load, but that translation is deprecated. This
script performs the same translation ahead of time and writes `dist/v2/agents/*.md`, which
the installers use when only OpenCode V2 is present.

The mapping mirrors OpenCode 2.x's own legacy translator:
  permission (map)        -> permissions (ordered list of {action, resource, effect})
  bash / task             -> shell / subagent
  write / patch           -> edit
  temperature / top_p     -> request.body.temperature / request.body.top_p
  disable / maxSteps      -> disabled / steps
  "list"                  -> dropped (no such tool in V2)
Rule order is preserved, so "last matching rule wins" keeps its meaning.

Commands need no translation: their frontmatter (description, agent) is the same in V2.

Usage:
  python3 scripts/build.py          # write dist/v2
  python3 scripts/build.py --check  # exit 1 if dist/v2 is missing or out of date
  python3 scripts/build.py --json   # print the V2 frontmatter of every agent as JSON
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "agents"
OUT = ROOT / "dist" / "v2" / "agents"

FRONTMATTER = re.compile(r"^---\r?\n(.*?)\r?\n---\r?\n(.*)$", re.S)
ACTION_RENAMES = {"bash": "shell", "task": "subagent", "write": "edit", "patch": "edit"}
V1_ONLY_ACTIONS = {"list"}
# Field order of the generated frontmatter.
V2_FIELDS = ("description", "mode", "hidden", "color", "model", "steps", "disabled", "request", "permissions")


class BuildError(Exception):
    pass


def split(text: str, name: str) -> tuple[dict, str]:
    match = FRONTMATTER.match(text)
    if not match:
        raise BuildError(f"{name}: missing YAML frontmatter")
    data = yaml.safe_load(match.group(1)) or {}
    if not isinstance(data, dict):
        raise BuildError(f"{name}: frontmatter must be a map")
    return data, match.group(2)


def to_rules(permission: object) -> list[dict]:
    if permission is None:
        return []
    if isinstance(permission, str):
        return [{"action": "*", "resource": "*", "effect": permission}]
    rules = []
    for action, rule in permission.items():
        if action in V1_ONLY_ACTIONS:
            continue
        action = ACTION_RENAMES.get(action, action)
        if isinstance(rule, str):
            rules.append({"action": action, "resource": "*", "effect": rule})
        else:
            rules.extend({"action": action, "resource": str(res), "effect": eff} for res, eff in rule.items())
    return rules


def to_v2(data: dict, name: str) -> dict:
    supported = {"description", "mode", "hidden", "color", "steps", "maxSteps", "disable",
                 "temperature", "top_p", "permission", "model", "variant"}
    unknown = sorted(set(data) - supported)
    if unknown:
        raise BuildError(f"{name}: no V2 mapping for frontmatter field(s) {unknown}")

    out: dict = {}
    for key in ("description", "mode", "hidden", "color"):
        if key in data:
            out[key] = data[key]
    if "model" in data:
        out["model"] = data["model"] + (f"#{data['variant']}" if data.get("variant") else "")
    steps = data.get("steps", data.get("maxSteps"))
    if steps is not None:
        out["steps"] = steps
    if "disable" in data:
        out["disabled"] = data["disable"]
    body = {k: data[k] for k in ("temperature", "top_p") if k in data}
    if body:
        out["request"] = {"body": body}
    rules = to_rules(data.get("permission"))
    if rules:
        out["permissions"] = rules
    return {k: out[k] for k in V2_FIELDS if k in out}


def scalar(value: object) -> str:
    # JSON scalars are valid YAML flow scalars, and quoting every string keeps
    # patterns like "*" or "git push *+*" from being read as YAML syntax.
    return json.dumps(value, ensure_ascii=False)


def render(source: Path) -> tuple[dict, str]:
    data, body = split(source.read_text(encoding="utf-8"), source.name)
    v2 = to_v2(data, source.name)
    lines = [
        "---",
        f"# Generated by scripts/build.py from agents/{source.name} for OpenCode V2. Do not edit.",
    ]
    for key, value in v2.items():
        if key == "request":
            lines.append("request:")
            lines.append("  body:")
            lines.extend(f"    {k}: {scalar(v)}" for k, v in value["body"].items())
        elif key == "permissions":
            lines.append("permissions:")
            lines.extend(
                f"  - {{ action: {scalar(r['action'])}, resource: {scalar(r['resource'])}, effect: {scalar(r['effect'])} }}"
                for r in value
            )
        else:
            lines.append(f"{key}: {scalar(value)}")
    lines.append("---")
    return v2, "\n".join(lines) + "\n" + body


def build() -> dict[str, tuple[dict, str]]:
    return {src.name: render(src) for src in sorted(SRC.glob("*.md"))}


def main(argv: list[str]) -> int:
    try:
        outputs = build()
    except BuildError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if "--json" in argv:
        print(json.dumps({Path(n).stem: fm for n, (fm, _) in outputs.items()}, indent=2, ensure_ascii=False))
        return 0

    if "--check" in argv:
        stale = [n for n, (_, text) in outputs.items()
                 if not (OUT / n).is_file() or (OUT / n).read_text(encoding="utf-8") != text]
        extra = sorted(p.name for p in OUT.glob("*.md") if p.name not in outputs) if OUT.is_dir() else []
        for n in stale:
            print(f"error: dist/v2/agents/{n} is out of date")
        for n in extra:
            print(f"error: dist/v2/agents/{n} has no source in agents/")
        if stale or extra:
            print("Run: python3 scripts/build.py")
            return 1
        print(f"dist/v2 is up to date ({len(outputs)} agents)")
        return 0

    OUT.mkdir(parents=True, exist_ok=True)
    for path in OUT.glob("*.md"):
        if path.name not in outputs:
            path.unlink()
    for name, (_, text) in outputs.items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(outputs)} agents to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
